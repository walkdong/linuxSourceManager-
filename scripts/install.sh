#!/bin/sh
# Source Manager installer - one line, no package manager, any distro.
#
#   curl -fsSL https://raw.githubusercontent.com/<you>/source-manager/main/scripts/install.sh | sh
#
# What it does, in order:
#   1. finds a Python >= 3.10 (refuses politely if there is none, with a way forward)
#   2. creates an isolated virtual environment under ~/.local/share/source-manager/venv
#      (your system Python is never modified, nothing is installed system-wide)
#   3. installs the `source-manager` package into it
#   4. puts a small `srcmgr` launcher in ~/.local/bin
#   5. creates the desktop entry, so it can be opened from the application menu
#
# Options (via environment):
#   SRCMGR_VERSION=v0.2.0      install a specific release (default: latest on PyPI)
#   SRCMGR_FROM=github         install from the GitHub release wheel instead of PyPI
#   SRCMGR_FROM=wheel          install a wheel you already have (SRCMGR_WHEEL=./x.whl);
#                              handy for offline installs, a network drive, or testing
#   SRCMGR_PREFIX=~/.local     where the launcher goes
#   SRCMGR_NO_SHORTCUT=1       do not create the desktop entry
#   SRCMGR_NO_PATH_HINT=1      never print the PATH advice
#
# Flags: --uninstall   remove everything this script created
set -eu

PREFIX="${SRCMGR_PREFIX:-$HOME/.local}"
BIN_DIR="$PREFIX/bin"
DATA_DIR="${XDG_DATA_HOME:-$HOME/.local/share}/source-manager"
VENV="$DATA_DIR/venv"
PACKAGE="source-manager"
REPO_SLUG="${SRCMGR_REPO:-source-manager/source-manager}"
VERSION="${SRCMGR_VERSION:-}"

say()  { printf '%s\n' "$*"; }
warn() { printf 'warning: %s\n' "$*" >&2; }
die()  { printf 'error: %s\n' "$*" >&2; exit 1; }

# ---------------------------------------------------------------- uninstall
if [ "${1:-}" = "--uninstall" ]; then
    say "Removing Source Manager…"
    rm -rf "$DATA_DIR"
    rm -f "$BIN_DIR/srcmgr"
    rm -f "${XDG_DATA_HOME:-$HOME/.local/share}/applications/source-manager.desktop"
    command -v update-desktop-database >/dev/null 2>&1 &&
        update-desktop-database "${XDG_DATA_HOME:-$HOME/.local/share}/applications" 2>/dev/null || true
    say "Done. Your source configuration (config.yaml, backups, history) was left in place"
    say "on purpose; delete ~/.config/source-manager and ~/.local/share/source-manager"
    say "if you want those gone too."
    exit 0
fi

# ------------------------------------------------------------------ python
find_python() {
    for candidate in python3.13 python3.12 python3.11 python3.10 python3; do
        if command -v "$candidate" >/dev/null 2>&1; then
            if "$candidate" -c 'import sys; raise SystemExit(0 if sys.version_info >= (3,10) else 1)' 2>/dev/null; then
                printf '%s' "$candidate"
                return 0
            fi
        fi
    done
    return 1
}

PY="$(find_python || true)"
if [ -z "$PY" ]; then
    cat >&2 <<'EOF'
error: no Python 3.10 or newer was found.

Two ways forward:
  * install Python (Debian/Ubuntu:  sudo apt install python3 python3-venv)
  * or use the single-file download, which needs no Python at all:
    grab srcmgr-linux-x86_64 from the Releases page, then
        chmod +x srcmgr-linux-x86_64 && ./srcmgr-linux-x86_64
EOF
    exit 1
fi
say "Using $PY ($("$PY" -c 'import platform; print(platform.python_version())'))"

# -------------------------------------------------------------------- venv
say "Installing into $VENV"
mkdir -p "$DATA_DIR" "$BIN_DIR"
if [ ! -x "$VENV/bin/python" ]; then
    "$PY" -m venv "$VENV" || die "could not create the virtual environment (is python3-venv installed?)"
fi
"$VENV/bin/python" -m pip install --quiet --upgrade pip

SPEC="${PACKAGE}"
if [ -n "$VERSION" ]; then
    SPEC="${PACKAGE}==${VERSION#v}"
fi
if [ "${SRCMGR_FROM:-pypi}" = "wheel" ]; then
    [ -n "${SRCMGR_WHEEL:-}" ] || die "SRCMGR_FROM=wheel needs SRCMGR_WHEEL=/path/to/source_manager-*.whl"
    [ -f "$SRCMGR_WHEEL" ] || die "wheel not found: $SRCMGR_WHEEL"
    say "Installing from a local wheel: $SRCMGR_WHEEL"
    "$VENV/bin/pip" install --quiet --upgrade "$SRCMGR_WHEEL"
elif [ "${SRCMGR_FROM:-pypi}" = "github" ]; then
    PIP_INDEX="--index-url https://github.com/${REPO_SLUG}/releases/latest/download/"
    warn "installing from the GitHub release index ($PIP_INDEX)"
    "$VENV/bin/pip" install --quiet --upgrade $PIP_INDEX "$SPEC" ||
        "$VENV/bin/pip" install --quiet --upgrade "$SPEC"
else
    "$VENV/bin/pip" install --quiet --upgrade "$SPEC"
fi

# ----------------------------------------------------------------- launcher
cat > "$BIN_DIR/srcmgr" <<EOF
#!/bin/sh
# Generated by the Source Manager installer; safe to delete.
exec "$VENV/bin/srcmgr" "\$@"
EOF
chmod +x "$BIN_DIR/srcmgr"
say "Command installed: $BIN_DIR/srcmgr"

# ----------------------------------------------------------- desktop entry
if [ "${SRCMGR_NO_SHORTCUT:-0}" != "1" ]; then
    "$VENV/bin/srcmgr" --install-shortcut >/dev/null 2>&1 &&
        say "Desktop entry created - it is now in your application menu." ||
        warn "could not create the desktop entry; run '$BIN_DIR/srcmgr --install-shortcut' later"
fi

# --------------------------------------------------------------------- PATH
case ":$PATH:" in
    *":$BIN_DIR:"*) ;;
    *)
        if [ "${SRCMGR_NO_PATH_HINT:-0}" != "1" ]; then
            cat <<EOF

Note: $BIN_DIR is not in your PATH, so typing "srcmgr" in a terminal will not work yet.
The application menu works regardless. To add it, run:

    echo 'export PATH="\$HOME/.local/bin:\$PATH"' >> ~/.profile && . ~/.profile
EOF
        fi
        ;;
esac

cat <<EOF

Installed. Two ways to start it:
  * open "源管理器" / "Source Manager" from your application menu (easiest)
  * or run: $BIN_DIR/srcmgr

Uninstall any time with:  sh "$0" --uninstall
EOF
